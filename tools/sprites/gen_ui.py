# Pequeñas correcciones: se permite un espacio por error en un mapa; normalizar a '.'
for k, rows in ICONS.items():
    ICONS[k] = [r.replace(" ", ".") for r in rows]


def main():
    os.makedirs(UI_DIR, exist_ok=True)
    preview = os.environ.get("SPRITE_PREVIEW_DIR")
    imgs = []
    for name, rows in ICONS.items():
        img = outline(grid(rows, K), P["outline"])
        img.save(os.path.join(UI_DIR, f"{name}.png"))
        imgs.append(img.resize((img.width, img.height)))
    # Cursor del ratón: mira de 12x12 ampliada x2 (los cursores CSS no se escalan)
    from PIL import Image
    cur = outline(grid(CURSOR, K), P["outline"])
    cur.resize((cur.width * 2, cur.height * 2), Image.NEAREST).save(os.path.join(UI_DIR, "cursor.png"))
    if preview:
        os.makedirs(preview, exist_ok=True)
        padded = []
        for im in imgs:
            c = Image.new("RGBA", (14, 14), (58, 58, 74, 255))
            c.alpha_composite(im, ((14 - im.width) // 2, (14 - im.height) // 2))
            padded.append(c)
        sh = sheet(padded, 10)
        sh.resize((sh.width * 6, sh.height * 6), Image.NEAREST).save(os.path.join(preview, "ui_icons.png"))
    print(f"{len(ICONS)} iconos -> {UI_DIR}")


if __name__ == "__main__":
    main()
